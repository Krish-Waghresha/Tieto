import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
import { fileURLToPath } from 'node:url'

const target = process.argv[2] ?? new URL('../out/invoice-import/preview.html', import.meta.url).href
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto(target)
  const metadata = await page.locator('#pr-metadata').evaluate(element => JSON.parse(element.textContent))
  if (metadata) {
    assert.equal(metadata.number, 3)
    await expect(page.locator('#pr-title')).toHaveText('INV-BULK-26: bulk invoice import')
    await expect(page.locator('#pr-number')).toHaveText('#3')
  }
  assert.equal((await page.locator('body').innerText()).includes('not connected yet'), false)
  await expect(page.locator('.graph-node')).toHaveCount(10)
  await expect(page.locator('.graph-node.green')).toHaveCount(5)
  await expect(page.locator('#change-count')).toContainText('1,618 added lines')
  for (const label of ['CsvInvoiceReader: Light review', 'DuplicatePolicy: Inspect behavior', 'RetryingInvoiceWriter: Human attention', 'TaxGateway: Insufficient evidence']) {
    await page.getByRole('button', { name: label, exact: true }).click()
    await expect(page.getByRole('button', { name: 'Inspect change', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Inspect change', exact: true }).click()
    await expect(page.locator('#diff-dialog')).toBeVisible()
    await page.getByRole('button', { name: 'Close diff', exact: true }).click()
    await page.getByRole('button', { name: 'Close details', exact: true }).click()
  }
  await page.getByRole('button', { name: 'DuplicatePolicy: Inspect behavior', exact: true }).click()
  await page.getByRole('radio', { name: 'Yes, block cancelled invoices', exact: true }).check()
  await page.getByRole('button', { name: 'Save answer & recompute', exact: true }).click()
  await expect(page.locator('#invoice-processing')).toBeVisible()
  await expect(page.locator('#invoice-result-title')).toHaveText('Policy clarified')
  await expect(page.locator('[data-id="module:DuplicatePolicy.cs"]')).toHaveAttribute('data-color', 'green')
  await expect(page.locator('#detail-status')).toHaveText('Light review')
  await expect(page.locator('#detail-facts dd').first()).toHaveText('97%')
  await page.getByRole('button', { name: 'Change answer', exact: true }).click()
  await page.getByRole('radio', { name: 'No, allow a replacement', exact: true }).check()
  await page.getByRole('button', { name: 'Save answer & recompute', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel recompute', exact: true }).click()
  await expect(page.locator('[data-id="module:DuplicatePolicy.cs"]')).toHaveAttribute('data-color', 'green')
  await expect(page.locator('[data-id="module:DuplicatePolicy.cs"] .node-status')).toHaveText('Policy clarified')
  await page.getByRole('button', { name: 'Save answer & recompute', exact: true }).click()
  await expect(page.locator('#invoice-result-title')).toHaveText('Policy change needed')
  await expect(page.locator('[data-id="module:DuplicatePolicy.cs"]')).toHaveAttribute('data-color', 'red')
  await page.getByRole('button', { name: 'Close details', exact: true }).click()
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 950 })
    await page.getByRole('button', { name: 'Fit', exact: true }).click()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `Page overflow at ${width}`)
    await page.getByRole('button', { name: 'RetryingInvoiceWriter: Human attention', exact: true }).click()
    await page.getByRole('button', { name: 'Understand', exact: true }).click()
    const bounds = await page.locator('#understand-dialog').boundingBox()
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width)
    if (width === 1440 || width === 390) await page.screenshot({ path: fileURLToPath(new URL(`../test-results/invoice-understand-${width}.png`, import.meta.url)) })
    await page.getByRole('button', { name: 'Close understanding view', exact: true }).click()
    await page.getByRole('button', { name: 'Close details', exact: true }).click()
  }
  await page.getByRole('button', { name: 'TaxGateway: Insufficient evidence', exact: true }).click()
  await page.getByRole('radio', { name: 'No provider contract is available', exact: true }).check()
  await page.getByRole('button', { name: 'Save answer & recompute', exact: true }).click()
  await expect(page.locator('#invoice-result-title')).toHaveText('Provider needs attention')
  await expect(page.locator('[data-id="module:TaxGateway.cs"]')).toHaveAttribute('data-color', 'red')
  await page.getByRole('button', { name: 'Change answer', exact: true }).click()
  await page.getByRole('radio', { name: 'Approved provider contract', exact: true }).check()
  await page.getByLabel('Provider contract reference', { exact: true }).fill('   ')
  await page.getByRole('button', { name: 'Save answer & recompute', exact: true }).click()
  await expect(page.locator('#invoice-processing')).toBeHidden()
  await page.getByLabel('Provider contract reference', { exact: true }).fill('docs/tax-contract.md')
  await page.getByRole('button', { name: 'Save answer & recompute', exact: true }).click()
  await expect(page.locator('#invoice-result-title')).toHaveText('Contract supplied')
  await expect(page.locator('[data-id="module:TaxGateway.cs"]')).toHaveAttribute('data-color', 'amber')
  await page.reload()
  await page.getByRole('button', { name: 'TaxGateway: Inspect behavior', exact: true }).click()
  await expect(page.locator('#invoice-result-reference')).toHaveText('docs/tax-contract.md')
  await page.getByRole('button', { name: 'Close details', exact: true }).click()
  await page.getByRole('button', { name: 'RetryingInvoiceWriter: Human attention', exact: true }).click()
  await page.getByRole('button', { name: 'Understand', exact: true }).click()
  await expect(page.locator('#understand-title')).toHaveText('RetryingInvoiceWriter.Write')
  await expect(page.locator('#after-outcome')).toHaveText('2 invoices')
  await page.getByRole('switch', { name: 'Reuse ID (proposed fix)', exact: true }).check()
  await expect(page.locator('#after-outcome')).toHaveText('1 invoice')
  await page.getByText('Check your understanding', { exact: true }).click()
  await page.getByRole('radio', { name: 'A second invoice with a new ID', exact: true }).check()
  await page.getByRole('button', { name: 'Check answer', exact: true }).click()
  await expect(page.locator('#access-quiz-feedback')).toContainText('Correct.')
  await page.getByText('Audio explanation', { exact: true }).click()
  await expect(page.locator('#access-transcript')).toContainText('acknowledgement is lost')
  await page.locator('#access-audio').evaluate(element => { element.muted = true; return element.play() })
  await expect.poll(() => page.locator('#access-audio').evaluate(element => element.currentTime)).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Close understanding view', exact: true }).click()
  await page.getByRole('button', { name: 'Close details', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 950 })
  await page.getByRole('button', { name: 'Fit', exact: true }).click()
  await page.screenshot({ path: fileURLToPath(new URL('../test-results/invoice-overview.png', import.meta.url)), fullPage: true })
  assert.deepEqual(errors, [])
  console.log('Invoice module overview and source inspection passed.')
} finally { await browser.close() }