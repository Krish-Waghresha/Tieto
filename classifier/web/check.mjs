      const bounds = await page.locator('#detail').boundingBox()
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width, `Amber card overflow at ${width}`)
      if (width < 650) await expect(page.getByRole('button', { name: 'Add concern', exact: true })).toBeInViewport()
