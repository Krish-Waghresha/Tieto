      await page.getByRole('button', { name: /^Shipping\.Quote:/ }).click()
      const bounds = await page.locator('#detail').boundingBox()
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width, `Gray card overflow at ${width}`)
      if (width === 1440 || width === 390) await page.screenshot({ path: fileURLToPath(new URL(`gray-result-${width}.png`, output)) })
      await page.getByRole('button', { name: 'Change response', exact: true }).click()
      if (width === 1440 || width === 390) await page.screenshot({ path: fileURLToPath(new URL(`gray-question-${width}.png`, output)) })
