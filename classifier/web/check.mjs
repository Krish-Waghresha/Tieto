      await expect(page.locator('#diff-method')).toHaveText(amberBlock.label)
      const diffBounds = await page.locator('#diff-dialog').boundingBox()
      assert.ok(diffBounds.x >= 0 && diffBounds.x + diffBounds.width <= width, `Amber diff overflow at ${width}`)
      await page.getByRole('button', { name: 'Close diff', exact: true }).click()
      await page.getByRole('button', { name: 'Close details' }).click()
