      assert.ok(diffBounds.x >= 0 && diffBounds.x + diffBounds.width <= width, `Diff overflow at ${width}`)
      if (width === 1440 || width === 390) await page.screenshot({ path: fileURLToPath(new URL(`green-diff-${width}.png`, output)) })
      await page.getByRole('button', { name: 'Close diff', exact: true }).click()
      await page.getByRole('button', { name: 'Close details' }).click()
